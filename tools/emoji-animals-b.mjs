// Pixel mask helpers: ink is the whole silhouette, the fill is the silhouette eroded by one pixel
const blank = size => new Uint8Array(size * size)
// Integers from a up to but not including b
const range = (a, b) => Array.from({ length: b - a }, (_, i) => a + i)
// Mask of every pixel inside any of the paths
const union = (size, ...paths) => {
  const m = blank(size)
  for (const p of paths) rasterise(p, size).forEach((v, i) => { if (v) m[i] = 1 })
  return m
}
// Pixels in either mask
const or = (...ms) => ms[0].map((_, i) => ms.some(m => m[i]) ? 1 : 0)
// Pixels in the first mask and not the second
const sub = (a, b) => a.map((v, i) => v && !b[i] ? 1 : 0)
// Pixels of a mask whose four neighbours are all set
const erode = (m, size) => {
  const out = blank(size)
  const at = (x, y) => x >= 0 && y >= 0 && x < size && y < size && m[y * size + x] === 1
  for (const y of range(0, size)) for (const x of range(0, size)) {
    if (at(x, y) && at(x - 1, y) && at(x + 1, y) && at(x, y - 1) && at(x, y + 1)) out[y * size + x] = 1
  }
  return out
}
// Mask grown by one pixel
const dilate = (m, size) => {
  const out = blank(size)
  const at = (x, y) => x >= 0 && y >= 0 && x < size && y < size && m[y * size + x] === 1
  for (const y of range(0, size)) for (const x of range(0, size)) {
    if (at(x, y) || at(x - 1, y) || at(x + 1, y) || at(x, y - 1) || at(x, y + 1)) out[y * size + x] = 1
  }
  return out
}
// Mask to a path of row runs
const path = (m, size) => {
  let d = ''
  for (const y of range(0, size)) {
    let x = 0
    while (x < size) {
      let w = 0
      while (x + w < size && m[y * size + x + w]) w++
      if (w) d += r(x, y, w, 1)
      x += w || 1
    }
  }
  return d
}
// Ellipse mask centred on cx, cy with radii rx, ry, tested at pixel centres
const ell = (size, cx, cy, rx, ry, deg = 0) => {
  const m = blank(size), c = Math.cos(deg * Math.PI / 180), s = Math.sin(deg * Math.PI / 180)
  for (const y of range(0, size)) for (const x of range(0, size)) {
    const px = x + 0.5 - cx, py = y + 0.5 - cy
    const dx = (px * c + py * s) / rx, dy = (py * c - px * s) / ry
    if (dx * dx + dy * dy <= 1) m[y * size + x] = 1
  }
  return m
}
// Ring mask one pixel thick
const ring = (size, d, ox, oy) => sub(union(size, circle(d, ox, oy)), union(size, circle(d - 2, ox + 1, oy + 1)))
// Outlined surface from a silhouette mask
const body = (size, m, fill) => [F(ink, path(m, size)), S(fill, path(erode(m, size), size))]
// Dark body: solid ink with a g1 rim along the top left of the interior
const dark = (size, m) => {
  const e = erode(m, size), rim = blank(size)
  for (const y of range(0, size)) for (const x of range(0, size)) {
    if (!e[y * size + x]) continue
    if (!e[(y - 1) * size + x] || !e[y * size + x - 1]) rim[y * size + x] = 1
  }
  return [F(ink, path(m, size)), F(g1, path(rim, size))]
}
// Shorthand for union
const M = (size, ...paths) => union(size, ...paths)
// Thin flat shape with an ink outline grown around it
const line = (size, fill, ...paths) => {
  const m = union(size, ...paths)
  return [F(ink, path(dilate(m, size), size)), F(fill, path(m, size))]
}
// Stem: ink sides around a green core
const stem = (x, y, w, h) => [F(ink, r(x, y, w + 2, h)), w > 1 ? S(gr2, r(x + 1, y, w, h)) : F(gr2, r(x + 1, y, w, h))]

// Five petal flower: petals around a centre, returns the mask
const petals = (size, cx, cy, dist, pr) => {
  let m = blank(size)
  for (const i of range(0, 5)) {
    const a = -Math.PI / 2 + i * 2 * Math.PI / 5
    m = or(m, ell(size, cx + dist * Math.cos(a), cy + dist * Math.sin(a), pr, pr))
  }
  return m
}

