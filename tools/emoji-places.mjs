// Mask helpers: the silhouette is the ink layer, the silhouette eroded by one pixel is the surface
const blank = size => new Uint8Array(size * size)
// Integers from a up to but not including b
const range = (a, b) => Array.from({ length: b - a }, (_, i) => a + i)
// Mask of every pixel inside any of the paths
const union = (size, ...paths) => {
  const m = blank(size)
  for (const p of paths) rasterise(p, size).forEach((v, i) => { if (v) m[i] = 1 })
  return m
}
// Mask with the paths cleared
const cut = (m, size, ...paths) => {
  const out = new Uint8Array(m)
  for (const p of paths) rasterise(p, size).forEach((v, i) => { if (v) out[i] = 0 })
  return out
}
// Pixels of a mask whose four neighbours are all set
const erode = (m, size) => {
  const out = blank(size)
  const at = (x, y) => x >= 0 && y >= 0 && x < size && y < size && m[y * size + x] === 1
  for (const y of range(0, size)) for (const x of range(0, size)) {
    if (at(x, y) && at(x - 1, y) && at(x + 1, y) && at(x, y - 1) && at(x, y + 1)) out[y * size + x] = 1
  }
  return out
}
// Mask to a path of row runs
const path = (m, size) => {
  let d = ''
  for (const y of range(0, size)) {
    let x = 0
    while (x < size) {
      let w = 0
      while (x + w < size && m[y * size + x + w]) w++
      if (w) d += r(x, y, w, 1)
      x += w || 1
    }
  }
  return d
}
// ink silhouette plus bevelled fill, from paths or a ready mask
const shapeM = (size, fill, m) => [F(ink, path(m, size)), S(fill, path(erode(m, size), size))]
const shape = (size, fill, ...paths) => shapeM(size, fill, union(size, ...paths))
// rows of [x0, x1] inclusive spans starting at y0
const rows = (y0, spans) => spans.map(([a, b], i) => r(a, y0 + i, b - a + 1, 1)).join('')
// 45 degree cone with an apex of width 2 at cx, n rows tall
const cone = (cx, top, n) => range(0, n).map(i => r(cx - i, top + i, 2 + 2 * i, 1)).join('')
// pixels in a rect where fn(x, y) holds
const pattern = (x0, y0, w, h, fn) => {
  let d = ''
  for (const y of range(y0, y0 + h)) for (const x of range(x0, x0 + w)) if (fn(x, y)) d += r(x, y, 1, 1)
  return d
}
// Diagonal stripes, on pixels out of every period
const stripes = (x0, y0, w, h, period, on) => pattern(x0, y0, w, h, (x, y) => ((x - y) % period + period) % period < on)
// union of paths plus their mirror across the vertical axis x -> c - x
const mirrorX = (size, c, ...paths) => {
  const m = union(size, ...paths), out = new Uint8Array(m)
  for (const y of range(0, size)) for (const x of range(0, size)) if (m[y * size + x]) out[y * size + (c - x)] = 1
  return out
}
// columns given as [x, y0, y1] inclusive
const spans = cols => cols.map(([x, y0, y1]) => r(x, y0, 1, y1 - y0 + 1)).join('')

