// Mask helpers: the silhouette is the ink, the fill is the silhouette eroded by one pixel
const range = (a, b) => Array.from({ length: b - a }, (_, i) => a + i)
// Mask of every pixel inside any of the paths
const union = (size, ...paths) => {
  const m = new Uint8Array(size * size)
  for (const p of paths) rasterise(p, size).forEach((v, i) => { if (v) m[i] = 1 })
  return m
}
// Pixels of a mask whose four neighbours are all set
const erode = (m, size) => {
  const out = new Uint8Array(size * size)
  const at = (x, y) => x >= 0 && y >= 0 && x < size && y < size && m[y * size + x] === 1
  for (const y of range(0, size)) for (const x of range(0, size)) {
    if (at(x, y) && at(x - 1, y) && at(x + 1, y) && at(x, y - 1) && at(x, y + 1)) out[y * size + x] = 1
  }
  return out
}
// Mask to a path of row runs
const path = (m, size) => {
  let d = ''
  for (const y of range(0, size)) {
    let x = 0
    while (x < size) {
      let w = 0
      while (x + w < size && m[y * size + x + w]) w++
      if (w) d += r(x, y, w, 1)
      x += w || 1
    }
  }
  return d
}
// rows(y0, [[x, w], ...]) stacks one pixel tall runs downward. Several runs per row are allowed as [[x, w], [x, w]]
const rows = (y0, spec) => spec.map((row, i) => (Array.isArray(row[0]) ? row : [row]).map(([x, w]) => r(x, y0 + i, w, 1)).join('')).join('')
// mirror a rows spec horizontally inside a canvas
const flip = (spec, size) => spec.map(row => (Array.isArray(row[0]) ? row : [row]).map(([x, w]) => [size - x - w, w]))
// rounded rectangle, ins lists the inset of each corner row from the top, mirrored at the bottom
const rr = (x, y, w, h, ins) => rows(y, [...ins.map(i => [x + i, w - 2 * i]), ...range(0, h - 2 * ins.length).map(() => [x, w]), ...[...ins].reverse().map(i => [x + i, w - 2 * i])])
// ink outlined bevelled shape
const body = (size, colour, ...paths) => {
  const m = union(size, ...paths)
  return [F(ink, path(m, size)), S(colour, path(erode(m, size), size))]
}
// ink outlined flat shape
const flat = (size, colour, ...paths) => {
  const m = union(size, ...paths)
  return [F(ink, path(m, size)), F(colour, path(erode(m, size), size))]
}
// One pixel rect
const dot = (x, y) => r(x, y, 1, 1)
// eyes with a single white specular pixel, 32 only
const eyes32 = (lx, rx, y, s = 3) => [F(ink, r(lx, y, s, s), r(rx, y, s, s)), F(white, dot(lx + 1, y + 1), dot(rx + 1, y + 1))]

